'use strict';
/* Regression: live section and fluid route must remain visible and animate. */
const fs = require('fs'), vm = require('vm'), assert = require('assert'), path = require('path');
global.window = global;
global.THREE = require('../lib/three.min.js');
global.document = { addEventListener(){}, getElementById(){ return null; }, createElement(){ return { getContext(){ return { fillRect(){}, strokeRect(){}, fillText(){} }; } }; } };
require('../lib/aro-pumpstandard.js');
require('../lib/aro-pumplivepanel.js');
require('../lib/aro-pumpoperating.js');
require('../lib/aro-pumpliveflow.js');
const app = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
vm.runInThisContext(app.slice(app.indexOf('  var PUMP_CASE_COLOR ='), app.indexOf('  function initPumpLiveViewer3D(container)')));
const duty = { Q_m3h: 20, H_m: 40, motorKw: 5, suctionPressureBarA: 1.1, dischargePressureBarG: 3, pumpElevationM: 0, dischargeElevationM: 10, densityKgM3: 998, viscosityCp: 1, speedRpm: 1450, fluidLabel: 'Water' };
const nozzles = { suction: 'DN50', discharge: 'DN40', suctionIdMm: 52.5, dischargeIdMm: 40.9 };
const panel = AROPUMPLIVEPANEL.buildLivePumpPanelData({ familyId: 'vane-pump', duty, nozzles });
const built = pumpLiveArchetypeMesh(panel.archetype.key, panel.familyId, { motorKw: 5, sucIdMm: 52.5, disIdMm: 40.9 });
AROPUMPOPERATING.decorate(panel, built);
const overlay = built.group.userData.liveFluidOverlay;
assert(overlay, 'live fluid overlay is attached to the selected pump');
const tracers = overlay.children.filter(x => x.userData && x.userData.flowTracer);
assert.strictEqual(tracers.length, 24, 'visible stream has 24 tracer slugs');
assert(overlay.children.some(x => x.userData && /Fluid core/.test(x.userData.partName || '')), 'fluid core exists');
assert(built.flowPath.getLength() > 0, 'vane route has a non-zero suction-to-discharge length');
let nearest = Infinity;
for (let i = 0; i <= 100; i++) nearest = Math.min(nearest, built.flowPath.getPointAt(i / 100).distanceTo(new THREE.Vector3(0.08, 0.9, 0)));
assert(nearest < 0.05, 'vane route crosses the eccentric rotor, not a generic empty-space shortcut');
const viewer = { rotorGroup: built.rotor, currentGroup: built.group, operatingPanel: panel, flowSimOn: true, flowSpeedMul: 1 };
AROPUMPOPERATING.animate(viewer, 1);
const before = tracers[0].position.clone();
AROPUMPOPERATING.animate(viewer, 3);
assert(before.distanceTo(tracers[0].position) > 1e-6, 'fluid tracer advances along the route');
overlay.traverse(node => { if (node.geometry) assert([...node.geometry.attributes.position.array].every(Number.isFinite)); });
console.log('PASS live fluid overlay: section core, vane route and moving tracers');
